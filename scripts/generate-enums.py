#!/usr/bin/env python3
"""Generate src/enums/*.ts: every enum of both Zoom SDKs as JS constants.

Usage: generate-enums.py <android-inventory.json> <ios-inventory.json>
(the SDK inventories built from `javap -public` of mobilertc's classes.jar and
from MobileRTC.framework/Headers).

iOS sends enums across the bridge as bare numbers, Android as constant names
(and, for audio/video status, ordinals too); these tables turn either into
something readable without a native change.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/enums"


def main():
    android = json.loads(Path(sys.argv[1]).read_text())
    ios = json.loads(Path(sys.argv[2]).read_text())
    OUT.mkdir(exist_ok=True)

    a_enums = android["enums"] if isinstance(android["enums"], list) else list(android["enums"].values())
    lines = [
        "// AUTO-GENERATED by scripts/generate-enums.py from the Zoom Android SDK. Do not edit.",
        "/** Every enum of the Android SDK: constant names in declaration order (index = ordinal). */",
        "export const ZoomAndroidEnums = {",
    ]
    for e in sorted(a_enums, key=lambda e: e["name"]):
        name = e["name"].split(".")[-1].replace("$", "_")
        consts = e.get("constants") or e.get("values") or []
        consts = [c if isinstance(c, str) else c["name"] for c in consts]
        lines.append(f"  {name}: [{', '.join(json.dumps(c) for c in consts)}],")
    lines += ["} as const;", ""]
    (OUT / "android.ts").write_text("\n".join(lines))

    i_enums = ios["enums"] if isinstance(ios["enums"], list) else list(ios["enums"].values())
    lines = [
        "// AUTO-GENERATED by scripts/generate-enums.py from MobileRTC headers. Do not edit.",
        "/** Every NS_ENUM / NS_OPTIONS of the iOS SDK: constant name -> value. */",
        "export const ZoomIosEnums = {",
    ]
    for e in sorted(i_enums, key=lambda e: e["name"]):
        if not e["name"].isidentifier():
            continue
        lines.append(f"  {e['name']}: {{")
        for c in e["constants"]:
            if c.get("value") is None:
                continue
            lines.append(f"    {json.dumps(c['name'])}: {c['value']},")
        lines.append("  },")
    lines += ["} as const;", ""]
    (OUT / "ios.ts").write_text("\n".join(lines))
    print(f"wrote src/enums/android.ts ({len(a_enums)} enums), src/enums/ios.ts ({len(i_enums)} enums)")


if __name__ == "__main__":
    main()
